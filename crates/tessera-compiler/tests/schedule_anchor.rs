/// RFC-0072 'Graphs without layers': their stacked forms, and the padded layers of a public tensor
/// and of a lookup non-zero at padding, are not specified.
const TEMPLATE: &str = "a layer template holds no ConstAdd, selection, ConstMul per channel, \
                        BitDecompose, AssertEqual, lookup non-zero at padding or node whose \
                        output is public";
/// RFC-0072 'Linear operations that are not coordinate maps': 'A committed output'.
const COMMITTED: &str = "a committed output is of a ConstMul, ConstAdd, Add, Sub or Mul";
/// RFC-0072 'Linear operations that are not coordinate maps': 'Summing relations'.
const SUMS: &str = "a Sum, SumSquares or MatMulAct over an axis whose length is not a power of \
                    two sums an input that is 0 at its padded positions";
/// RFC-0045 'The split' sends no value for a lookup's public input; the leaf layout still does.
const PUBLIC_SITE: &str = "a leaf site reads no public tensor: the leaf layout does not leave its \
                           value out of the split yet";
/// RFC-0072 'Public tensors' 'As an operand': a matmul reads no operand as `Public`.
const MATMUL: &str = "a matmul's operands are not public, unless both are";

/// The schedule of `graph` with no layers and no logits.
fn layerless(graph: &Graph, tables: &[TableSpec]) -> Result<StageSchedule, CompileError> {
    derive_graph_schedule(graph, tables, &[], None)
}

/// The rule of a schedule refused with `ERR-INTERNAL`.
fn refusal(result: Result<StageSchedule, CompileError>) -> &'static str {
    match result {
        Err(error @ CompileError::Schedule { rule, .. }) => {
            assert_eq!(error.code(), ErrorCode::Internal, "{rule}");
            rule
        }
        other => panic!("refused, not {other:?}"),
    }
}

/// A requantization by `2^4` of `key` into `[lo, hi]`: a gadget, whose input is a leaf site.
fn requant(g: &mut GraphBuilder, key: TensorId, shape: &[u32], lo: i64, hi: i64) -> TensorId {
    let shift = g.shift_classes(vec![4]).expect("a shift");
    let op = Op::Requant { shift, lo, hi };
    one(
        g,
        op,
        &[key],
        decl(shape, ADVICE, i128::from(lo), i128::from(hi)),
    )
}

fn mul() -> Op {
    Op::Mul {
        broadcast: Broadcast::Trailing,
    }
}

/// A table of `kind` with id `id`, its specification as the claim list states it.
fn spec(id: u32, kind: TableKind) -> TableSpec {
    GeneratedTable::new(TableId(id), kind)
        .expect("a table")
        .spec()
        .clone()
}

/// The AES S-box as table 0, whose value at 0 is `0x63`.
fn sbox() -> Vec<TableSpec> {
    vec![spec(0, TableKind::AesSbox)]
}

/// `AesSbox(x)`, elementwise.
fn substitute(g: &mut GraphBuilder, x: TensorId, shape: &[u32]) -> TensorId {
    one(
        g,
        Op::TableMap { table: TableId(0) },
        &[x],
        out(shape, NodeKind::LookupOutput { table: TableId(0) }),
    )
}

fn bytes(g: &mut GraphBuilder, shape: &[u32]) -> TensorId {
    g.input(decl(shape, ADVICE, 0, 255)).expect("bytes")
}

