/// RFC-0072 'In a model's graph': the template rule reads the layers alone. A prologue holding a
/// `Slice`, a `GatherPublic` and a public product, and an epilogue holding a `ConstAdd`, a `Slice`
/// and an S-box, all of the last checkpoint, pass it: the anchor's circuits are epilogue nodes. A
/// claim through the epilogue's `ConstAdd` then waits for `ConstAdd`'s relation (#526).
#[test]
fn the_template_rule_reads_the_layers_alone() {
    let build = |read: bool| {
        let mut g = GraphBuilder::new();
        let x = g.input(decl(&[4, 8], ADVICE, -100, 100)).expect("x");
        let p = g.input(decl(&[4, 8], NodeKind::Public, 0, 1)).expect("p");
        let cut = Op::Slice {
            axis: 0,
            start: 1,
            len: 2,
        };
        one(&mut g, cut.clone(), &[x], virt(&[2, 8]));
        let rows = g.constant(vec![3, 0]).expect("rows");
        one(
            &mut g,
            Op::GatherPublic { index: rows },
            &[x],
            virt(&[2, 8]),
        );
        one(&mut g, mul(), &[p, p], virt(&[4, 8]));
        let unit = g.constant(vec![1]).expect("a constant");
        let mut c = one(&mut g, Op::ConstMul { c: unit }, &[x], out(&[4, 8], ADVICE));
        let mut checkpoints = vec![c];
        for _ in 0..2 {
            let square = one(&mut g, mul(), &[c, c], virt(&[4, 8]));
            c = requant(&mut g, square, &[4, 8], -100, 100);
            checkpoints.push(c);
        }
        let three = g.constant(vec![3]).expect("a constant");
        let shifted = one(&mut g, Op::ConstAdd { c: three }, &[c], virt(&[4, 8]));
        one(&mut g, cut, &[c], virt(&[2, 8]));
        substitute(&mut g, c, &[4, 8]);
        if read {
            requant(&mut g, shifted, &[4, 8], -100, 100);
        }
        derive_graph_schedule(&g.finish(), &byte_tables(), &checkpoints, None)
    };
    let schedule = build(false).expect("the prologue and epilogue pass the template rule");
    assert_eq!(schedule.layers.count, 2);
    assert_eq!(
        refusal(build(true)),
        MAPS,
        "a claim through the epilogue's ConstAdd"
    );
}

/// A node a test adds to a graph of two committed `[4, 3]` tensors, its output committed.
type Committed = fn(&mut GraphBuilder, TensorId, TensorId);

/// RFC-0072 'A committed output': stage 1 proves a committed output of a `ConstMul`, `ConstAdd`,
/// `Add`, `Sub` or `Mul` only; any other's, a selection's, `Sum`'s, `SumSquares`'s, `Rotate`'s,
/// `Transpose`'s, `Reshape`'s or `Expand`'s, is refused when the schedule is derived, although the
/// IR admits it, even when no claim reaches it.
#[test]
fn a_committed_output_stage_1_does_not_prove_is_refused() {
    let graph = |node: Committed| {
        let mut g = GraphBuilder::new();
        let x = g.input(decl(&[4, 3], ADVICE, -100, 100)).expect("x");
        let y = g.input(decl(&[4, 3], ADVICE, -100, 100)).expect("y");
        node(&mut g, x, y);
        g.finish()
    };
    let refused: [(&str, Committed); 8] = [
        ("Slice", |g, x, _| {
            let op = Op::Slice {
                axis: 0,
                start: 1,
                len: 2,
            };
            one(g, op, &[x], out(&[2, 3], ADVICE));
        }),
        ("Sum", |g, x, _| {
            one(g, Op::Sum { axis: 0 }, &[x], out(&[3], ADVICE));
        }),
        ("GatherPublic", |g, x, _| {
            let index = g.constant(vec![1]).expect("a row");
            one(g, Op::GatherPublic { index }, &[x], out(&[1, 3], ADVICE));
        }),
        ("SumSquares", |g, x, _| {
            one(g, Op::SumSquares { axis: 0 }, &[x], out(&[3], ADVICE));
        }),
        ("Transpose", |g, x, _| {
            let op = Op::Transpose { perm: vec![1, 0] };
            one(g, op, &[x], out(&[3, 4], ADVICE));
        }),
        ("Expand", |g, x, _| {
            let op = Op::Expand { axis: 0, len: 2 };
            one(g, op, &[x], out(&[2, 4, 3], ADVICE));
        }),
        ("Reshape", |g, x, _| {
            one(g, Op::Reshape, &[x], out(&[12], ADVICE));
        }),
        ("Rotate", |g, _, _| {
            let x = g.input(decl(&[4, 2], ADVICE, -100, 100)).expect("pairs");
            let positions = g
                .input(decl(&[4], NodeKind::Public, 0, 3))
                .expect("positions");
            let op = Op::Rotate { rope: TableId(0) };
            one(g, op, &[x, positions], out(&[4, 2], ADVICE));
        }),
    ];
    for (name, node) in refused {
        assert_eq!(refusal(layerless(&graph(node), &[])), COMMITTED, "{name}");
    }
    let admitted: [(&str, Committed); 4] = [
        ("Add", |g, x, y| {
            one(g, Op::Add, &[x, y], out(&[4, 3], ADVICE));
        }),
        ("Sub", |g, x, y| {
            one(g, Op::Sub, &[x, y], out(&[4, 3], ADVICE));
        }),
        ("Mul", |g, x, y| {
            one(g, mul(), &[x, y], out(&[4, 3], ADVICE));
        }),
        ("ConstMul", |g, x, _| {
            let c = g.constant(vec![5]).expect("a constant");
            one(g, Op::ConstMul { c }, &[x], out(&[4, 3], ADVICE));
        }),
    ];
    for (name, node) in admitted {
        let schedule = layerless(&graph(node), &[]).unwrap_or_else(|e| panic!("{name}: {e:?}"));
        assert_eq!(schedule.stage_count(), 2, "{name}: its zero-check");
    }
    // A committed `ConstAdd` passes this rule; its zero-check's shift comes with `ConstAdd`'s.
    let shifted = graph(|g, x, _| {
        let c = g.constant(vec![5]).expect("a constant");
        one(g, Op::ConstAdd { c }, &[x], out(&[4, 3], ADVICE));
    });
    assert_eq!(refusal(layerless(&shifted, &[])), SHIFT);
}

/// The key a test computes from the S-box's output `s`, and its shape.
type Key<'a> = &'a dyn Fn(&mut GraphBuilder, TensorId) -> (TensorId, Vec<u32>);

/// The schedule of `x ↦ requant(key(AesSbox(x)))`, `x` bytes of `shape`.
fn summed(shape: &[u32], key: Key<'_>) -> Result<StageSchedule, CompileError> {
    let mut g = GraphBuilder::new();
    let x = bytes(&mut g, shape);
    let s = substitute(&mut g, x, shape);
    let (k, k_shape) = key(&mut g, s);
    requant(&mut g, k, &k_shape, -128, 127);
    layerless(&g.finish(), &sbox())
}

/// RFC-0072 'Summing relations': a `Sum`, `SumSquares` or `MatMulAct` over an axis that is not a
/// power of two needs an input it sums that is 0 at the axis's padded positions: no lookup
/// non-zero at padding upstream, or an `Expand` or a selection along that axis.
#[test]
fn a_sum_over_a_padded_axis_needs_an_input_zero_there() {
    let sum_of = summed;
    let sum = |axis: u8, out_shape: Vec<u32>| {
        move |g: &mut GraphBuilder, s: TensorId| {
            let k = one(g, Op::Sum { axis }, &[s], virt(&out_shape));
            (k, out_shape.clone())
        }
    };
    // Over the S-box's padded axis of 3: refused; over an axis of 4: admitted.
    assert_eq!(
        refusal(sum_of(&[4, 3], &sum(1, vec![4]))),
        SUMS,
        "Sum over 3"
    );
    sum_of(&[3, 4], &sum(1, vec![3])).expect("a Sum over 4");
    assert_eq!(
        refusal(sum_of(&[4, 3], &|g, s| {
            (
                one(g, Op::SumSquares { axis: 1 }, &[s], virt(&[4])),
                vec![4],
            )
        })),
        SUMS,
        "SumSquares over 3"
    );
    // Downstream of the lookup, through any node.
    assert_eq!(
        refusal(sum_of(&[4, 3], &|g, s| {
            let doubled = one(g, Op::Add, &[s, s], virt(&[4, 3]));
            (one(g, Op::Sum { axis: 1 }, &[doubled], virt(&[4])), vec![4])
        })),
        SUMS,
        "an Add of the S-box"
    );
    // An `Expand` along the summed axis is 0 past its length: admitted, and derived.
    sum_of(&[4], &|g, s| {
        let wide = one(g, Op::Expand { axis: 1, len: 3 }, &[s], virt(&[4, 3]));
        (one(g, Op::Sum { axis: 1 }, &[wide], virt(&[4])), vec![4])
    })
    .expect("a Sum along an Expand's axis");
    // Along another axis, it is not.
    assert_eq!(
        refusal(sum_of(&[4, 3], &|g, s| {
            let wide = one(g, Op::Expand { axis: 0, len: 2 }, &[s], virt(&[2, 4, 3]));
            (
                one(g, Op::Sum { axis: 2 }, &[wide], virt(&[2, 4])),
                vec![2, 4],
            )
        })),
        SUMS,
        "an Expand along another axis"
    );
    // A selection along the summed axis is 0 there: the summing rule admits it, and the claim then
    // waits for the selection relation.
    assert_eq!(
        refusal(sum_of(&[4, 4], &|g, s| {
            let op = Op::Slice {
                axis: 1,
                start: 1,
                len: 3,
            };
            let cut = one(g, op, &[s], virt(&[4, 3]));
            (one(g, Op::Sum { axis: 1 }, &[cut], virt(&[4])), vec![4])
        })),
        MAPS,
        "a Slice along the summed axis"
    );
    assert_eq!(
        refusal(sum_of(&[4, 2], &|g, s| {
            let index = g.constant(vec![0, 2, 3]).expect("rows");
            let picked = one(g, Op::GatherPublic { index }, &[s], virt(&[3, 2]));
            (one(g, Op::Sum { axis: 0 }, &[picked], virt(&[2])), vec![2])
        })),
        MAPS,
        "a GatherPublic along the summed axis"
    );
    assert_eq!(
        refusal(sum_of(&[4, 3], &|g, s| {
            let op = Op::Slice {
                axis: 0,
                start: 0,
                len: 2,
            };
            let cut = one(g, op, &[s], virt(&[2, 3]));
            (one(g, Op::Sum { axis: 1 }, &[cut], virt(&[2])), vec![2])
        })),
        SUMS,
        "a Slice along another axis"
    );
    // A gather selects the outermost axis's rows: along axis 1 it is no selection.
    assert_eq!(
        refusal(sum_of(&[4, 3], &|g, s| {
            let index = g.constant(vec![0, 2]).expect("rows");
            let picked = one(g, Op::GatherPublic { index }, &[s], virt(&[2, 3]));
            (one(g, Op::Sum { axis: 1 }, &[picked], virt(&[2])), vec![2])
        })),
        SUMS,
        "a GatherPublic, summed along axis 1"
    );
    // `MatMulAct` sums both inputs over its inner axis: one clean input suffices. A bare
    // committed input's padded positions are the prover's, so it is clean only when a `OneHot`
    // reads it directly or a `BitDecompose` reads it, directly or moved (RFC-0006 'Committed graph
    // inputs').
    for transposed in [false, true] {
        let product = |a: Operand, b: Operand, inner: u32| matmul(a, b, inner, transposed);
        let label = format!("transposed: {transposed}");
        assert_eq!(refusal(product(Dirty, Dirty, 3)), SUMS, "{label}");
        assert_eq!(
            refusal(product(Dirty, Bare, 3)),
            SUMS,
            "{label}: a bare right operand"
        );
        assert_eq!(
            refusal(product(Bare, Dirty, 3)),
            SUMS,
            "{label}: a bare left operand"
        );
        product(Dirty, Pinned, 3).expect("a pinned right operand");
        product(Pinned, Dirty, 3).expect("a pinned left operand");
        product(Dirty, Dirty, 4).expect("an inner axis of 4");
        // An `Expand` that forms the right operand is 0 past its length along its inner axis
        // only.
        expanded_right(transposed, true).expect("an Expand along the right operand's inner axis");
        assert_eq!(
            refusal(expanded_right(transposed, false)),
            SUMS,
            "{label}: an Expand along its outer axis"
        );
    }
    // A requantization non-zero at padding, `rq(0) = 1` into `[1, 255]`, is such a lookup; one
    // into `[−128, 127]` is not, but its bare input is, until a `OneHot` reads it.
    assert_eq!(refusal(requantized(1, 255, Bare)), SUMS);
    assert_eq!(refusal(requantized(-128, 127, Bare)), SUMS, "a bare input");
    requantized(-128, 127, Pinned).expect("rq(0) = 0 of a pinned input");
    assert_eq!(refusal(requantized(1, 255, Pinned)), SUMS, "rq(0) = 1");
}

/// How a test's operand reaches a relation: a bare committed input; one a `OneHot` reads
/// directly, which pins its padded positions; or an S-box of a bare input, non-zero at padding.
#[derive(Clone, Copy, Debug)]
enum Operand {
    Bare,
    Pinned,
    Dirty,
}
use Operand::{Bare, Dirty, Pinned};

/// An operand of `shape` of `kind`: committed bytes, pinned by a `OneHot` of 256, or their S-box.
fn operand(g: &mut GraphBuilder, shape: &[u32], kind: Operand) -> TensorId {
    let x = bytes(g, shape);
    match kind {
        Bare => x,
        Pinned => {
            let mut one_hot = shape.to_vec();
            one_hot.push(256);
            one(g, Op::OneHot { vocab: 256 }, &[x], out(&one_hot, ADVICE));
            x
        }
        Dirty => substitute(g, x, shape),
    }
}

/// The schedule of `requant(MatMulAct(a, b))` over an inner axis of `inner`, `[1, 2, inner]` by
/// `[1, inner, 2]`, or by `[1, 2, inner]` transposed.
fn matmul(
    a: Operand,
    b: Operand,
    inner: u32,
    transposed: bool,
) -> Result<StageSchedule, CompileError> {
    let mut g = GraphBuilder::new();
    let b_shape = if transposed {
        [1, 2, inner]
    } else {
        [1, inner, 2]
    };
    let a = operand(&mut g, &[1, 2, inner], a);
    let b = operand(&mut g, &b_shape, b);
    let op = Op::MatMulAct {
        transpose_rhs: transposed,
    };
    let z = one(&mut g, op, &[a, b], virt(&[1, 2, 2]));
    requant(&mut g, z, &[1, 2, 2], -128, 127);
    layerless(&g.finish(), &sbox())
}

/// The schedule of `requant(MatMulAct(a, B))` over an inner axis of 3, `a` an S-box output and
/// `B` an `Expand` of another, along `B`'s inner axis or along its outer one.
fn expanded_right(transposed: bool, along_inner: bool) -> Result<StageSchedule, CompileError> {
    let mut g = GraphBuilder::new();
    let a = operand(&mut g, &[1, 2, 3], Dirty);
    // `B` is `[1, 3, 2]` (inner axis 1), or `[1, 2, 3]` transposed (inner axis 2).
    let (inner, b_shape) = if transposed {
        (2, [1, 2, 3])
    } else {
        (1, [1, 3, 2])
    };
    let axis = if along_inner { inner } else { 3 - inner };
    let mut source = b_shape.to_vec();
    let len = source.remove(axis);
    let s = operand(&mut g, &source, Dirty);
    let axis = u8::try_from(axis).expect("small");
    let b = one(&mut g, Op::Expand { axis, len }, &[s], virt(&b_shape));
    let op = Op::MatMulAct {
        transpose_rhs: transposed,
    };
    let z = one(&mut g, op, &[a, b], virt(&[1, 2, 2]));
    requant(&mut g, z, &[1, 2, 2], -128, 127);
    layerless(&g.finish(), &sbox())
}

/// The schedule of `requant(Sum_1(requant_{[lo, hi]}(x)))`, `x` committed bytes `[4, 3]`.
fn requantized(lo: i64, hi: i64, x: Operand) -> Result<StageSchedule, CompileError> {
    let mut g = GraphBuilder::new();
    let x = operand(&mut g, &[4, 3], x);
    let r = requant(&mut g, x, &[4, 3], lo, hi);
    let k = one(&mut g, Op::Sum { axis: 1 }, &[r], virt(&[4]));
    requant(&mut g, k, &[4], -128, 127);
    layerless(&g.finish(), &sbox())
}

/// RFC-0072 'Padded positions' and RFC-0006 'Committed graph inputs': nothing computes a committed
/// graph input's padded positions, so a sum over a padded axis downstream of one is refused unless
/// an operation pins them: a `OneHot` reading it directly, or a `BitDecompose` reading it directly
/// or moved by `Reshape`, `Slice`, `Transpose`, `GatherPublic` or `Expand`, whose input padding
/// check pins them (slice 2). The summing rule runs before the bit operations' refusal, so a
/// `BitDecompose`'s pin shows as that refusal, `BITS`, rather than `SUMS`.
#[test]
fn a_committed_input_is_zero_at_padding_only_when_pinned() {
    // `requant(Sum_1(x))`, `x` committed `[4, 3]`, which `reader` reads too.
    let sum_with = |reader: fn(&mut GraphBuilder, TensorId)| {
        let mut g = GraphBuilder::new();
        let x = g.input(decl(&[4, 3], ADVICE, 0, 255)).expect("x");
        reader(&mut g, x);
        let k = one(&mut g, Op::Sum { axis: 1 }, &[x], virt(&[4]));
        requant(&mut g, k, &[4], -128, 127);
        layerless(&g.finish(), &[])
    };
    // The bits of `t`, of `shape`.
    fn decompose(g: &mut GraphBuilder, t: TensorId, shape: &[u32]) {
        let mut bits = shape.to_vec();
        bits.push(8);
        g.node(
            Op::BitDecompose { low: 8, high: 0 },
            &[t],
            vec![out(&bits, ADVICE)],
        )
        .expect("bits");
    }
    assert_eq!(refusal(sum_with(|_, _| {})), SUMS, "no reader");
    sum_with(|g, x| {
        one(
            g,
            Op::OneHot { vocab: 256 },
            &[x],
            out(&[4, 3, 256], ADVICE),
        );
    })
    .expect("a OneHot reads it directly");
    // A `OneHot` pins its own input's padded rows only: through a move they are not `x`'s.
    assert_eq!(
        refusal(sum_with(|g, x| {
            let flat = one(g, Op::Reshape, &[x], virt(&[12]));
            one(
                g,
                Op::OneHot { vocab: 256 },
                &[flat],
                out(&[12, 256], ADVICE),
            );
        })),
        SUMS,
        "a OneHot of a reshape"
    );
    assert_eq!(
        refusal(sum_with(|g, x| decompose(g, x, &[4, 3]))),
        BITS,
        "a BitDecompose reads it directly"
    );
    assert_eq!(
        refusal(sum_with(|g, x| {
            let turned = one(g, Op::Transpose { perm: vec![1, 0] }, &[x], virt(&[3, 4]));
            let flat = one(g, Op::Reshape, &[turned], virt(&[12]));
            decompose(g, flat, &[12]);
        })),
        BITS,
        "a BitDecompose reads it moved"
    );
    assert_eq!(
        refusal(sum_with(|g, x| {
            let index = g.constant(vec![1]).expect("a row");
            let row = one(g, Op::GatherPublic { index }, &[x], virt(&[1, 3]));
            let cut = Op::Slice {
                axis: 1,
                start: 0,
                len: 2,
            };
            let pair = one(g, cut, &[row], virt(&[1, 2]));
            let wide = one(g, Op::Expand { axis: 0, len: 2 }, &[pair], virt(&[2, 1, 2]));
            decompose(g, wide, &[2, 1, 2]);
        })),
        BITS,
        "a BitDecompose reads part of it, moved: its padding check covers the whole input"
    );
    // Through an `Add`, the decomposition reads another tensor.
    assert_eq!(
        refusal(sum_with(|g, x| {
            let doubled = one(g, Op::Add, &[x, x], virt(&[4, 3]));
            decompose(g, doubled, &[4, 3]);
        })),
        SUMS,
        "a BitDecompose of an Add"
    );
    // A weight is not advice: RFC-0048 vouches for its domain.
    let mut g = GraphBuilder::new();
    let w = g.input(decl(&[4, 3], WEIGHT, -127, 127)).expect("w");
    let k = one(&mut g, Op::Sum { axis: 1 }, &[w], virt(&[4]));
    requant(&mut g, k, &[4], -128, 127);
    layerless(&g.finish(), &[]).expect("a weight's sum");
}

/// `derive_graph_schedule` validates its graph (RFC-0006 'Operation set') before reading it: an
/// input id outside the graph is an error, not a panic.
#[test]
fn an_invalid_graph_is_an_error() {
    let mut g = GraphBuilder::new();
    let x = g.input(decl(&[4], ADVICE, -100, 100)).expect("x");
    requant(&mut g, x, &[4], -128, 127);
    let mut graph = g.finish();
    graph.nodes[0].inputs[0] = TensorId(99);
    assert!(matches!(
        layerless(&graph, &[]),
        Err(CompileError::Graph(_))
    ));
}

/// RFC-0072 'Padded positions': a `TableMap` or `Bitwise` is non-zero at padding when its table
/// maps the zero key, in some class, to a value other than 0, as `tessera_tables` generates it; a
/// `Requant` when `rq(0)` from its shifts and bounds is not 0 (RFC-0005).
#[test]
fn lookups_are_non_zero_at_padding_exactly_when_their_tables_say() {
    let scale = Rational::new(1, 16).expect("a scale");
    let kinds = [
        TableKind::AesSbox,
        TableKind::Gf256Mul { c: 2 },
        TableKind::Gf256Mul { c: 3 },
        TableKind::Range { bits: 4 },
        TableKind::Pow2 { max_exp: 4 },
        TableKind::Requant {
            b: 8,
            r_by_class: vec![2, 3],
            lo: -128,
            hi: 127,
        },
        TableKind::Requant {
            b: 8,
            r_by_class: vec![2],
            lo: 1,
            hi: 5,
        },
        TableKind::Exp {
            key_bits: 4,
            sigma: 8,
            scale,
        },
        TableKind::Exp2Frac {
            frac_bits: 4,
            out_bits: 8,
        },
        TableKind::Silu {
            b: 8,
            r_by_class: vec![2, 3],
            in_exp: -4,
            out_exp: 0,
        },
        TableKind::Bitwise8 { op: BitOp::Xor },
        TableKind::Bitwise8 { op: BitOp::And },
    ];
    let mut seen = [false; 2];
    for (id, kind) in (0u32..).zip(kinds) {
        let table = GeneratedTable::new(TableId(id), kind.clone()).expect("a table");
        let classes: u8 = match &kind {
            TableKind::Requant { r_by_class, .. } | TableKind::Silu { r_by_class, .. } => {
                u8::try_from(r_by_class.len()).expect("small")
            }
            _ => 1,
        };
        let expected = (0..classes).any(|c| table.lookup(0, c) != Some(0));
        let mut g = GraphBuilder::new();
        let x = g.input(decl(&[4], ADVICE, 0, 15)).expect("x");
        let output = out(&[4], NodeKind::LookupOutput { table: TableId(id) });
        let (op, inputs) = match kind {
            TableKind::Bitwise8 { .. } => (Op::Bitwise { table: TableId(id) }, vec![x, x]),
            _ if classes > 1 => {
                let c = g.input(decl(&[4], WEIGHT, 0, 1)).expect("classes");
                (Op::TableMap { table: TableId(id) }, vec![x, c])
            }
            _ => (Op::TableMap { table: TableId(id) }, vec![x]),
        };
        g.node(op, &inputs, vec![output]).expect("a lookup");
        let graph = g.finish();
        let specs = vec![table.spec().clone()];
        let node = graph.nodes.last().expect("the lookup");
        assert_eq!(
            nonzero_at_padding(&graph, &specs, node),
            Ok(expected),
            "{kind:?}"
        );
        seen[usize::from(expected)] = true;
    }
    assert_eq!(seen, [true, true], "both outcomes");
    // `Requant`'s `rq(0) = clamp(0, lo, hi)` in every class.
    for (shifts, lo, hi) in [
        (vec![4], -128, 127),
        (vec![4], 0, 255),
        (vec![1, 9], 1, 255),
        (vec![4], -9, -1),
        (vec![2, 3], -128, 127),
    ] {
        let mut g = GraphBuilder::new();
        let x = g.input(decl(&[4], ADVICE, -100, 100)).expect("x");
        let mut inputs = vec![x];
        if shifts.len() > 1 {
            inputs.push(g.input(decl(&[4], WEIGHT, 0, 1)).expect("classes"));
        }
        let expected = shifts.iter().any(|&r| rq(0, r, lo, hi) != 0);
        let shift = g.shift_classes(shifts.clone()).expect("shifts");
        let op = Op::Requant { shift, lo, hi };
        g.node(op, &inputs, vec![out(&[4], ADVICE)])
            .expect("a requantization");
        let graph = g.finish();
        let node = graph.nodes.last().expect("the requantization");
        assert_eq!(
            nonzero_at_padding(&graph, &[], node),
            Ok(expected),
            "{shifts:?} into [{lo}, {hi}]"
        );
    }
    // A lookup's table must be the graph's.
    let mut g = GraphBuilder::new();
    let x = bytes(&mut g, &[4]);
    substitute(&mut g, x, &[4]);
    let graph = g.finish();
    assert!(matches!(
        nonzero_at_padding(&graph, &[], &graph.nodes[0]),
        Err(CompileError::Schedule { .. })
    ));
}

/// Stage 1's bit zero-checks are not derived yet (#526's second slice): a graph with a
/// `BitDecompose` or an `AssertEqual` is refused, rather than given a schedule that proves neither.
/// Neither takes a leaf site (RFC-0072 'Gadgets and leaf sites'), so without the refusal SHA-256's
/// schedule would be its empty leaf stage alone.
#[test]
fn the_bit_operations_wait_for_their_zero_checks() {
    let mut g = GraphBuilder::new();
    let x = g.input(decl(&[4], ADVICE, 0, 255)).expect("x");
    g.node(
        Op::BitDecompose { low: 8, high: 0 },
        &[x],
        vec![out(&[4, 8], ADVICE)],
    )
    .expect("bits");
    assert_eq!(refusal(layerless(&g.finish(), &[])), BITS, "BitDecompose");
    let mut g = GraphBuilder::new();
    let x = g.input(decl(&[4], ADVICE, 0, 255)).expect("x");
    let p = g.input(decl(&[4], NodeKind::Public, 0, 255)).expect("p");
    g.node(Op::AssertEqual, &[x, p], Vec::new())
        .expect("an equality");
    assert_eq!(refusal(layerless(&g.finish(), &[])), BITS, "AssertEqual");
    let layout = Sha256Layout {
        blocks: 1,
        messages: 1,
        committed: Vec::new(),
    };
    let mut g = GraphBuilder::new();
    let inputs: Vec<TensorId> = sha256_inputs(&layout)
        .into_iter()
        .map(|d| g.input(d).expect("an input"))
        .collect();
    let sha = sha256(&mut g, &layout, &inputs).expect("the circuit");
    let digest = g.input(sha256_digest_input(1)).expect("the digest");
    sha256_bind(&mut g, sha.chaining.last().expect("a block"), digest, 1).expect("the binding");
    let graph = g.finish();
    assert_eq!(refusal(layerless(&graph, &[])), BITS, "SHA-256");
    assert_eq!(
        stage_count(&graph),
        10,
        "the report counts RFC-0072's stages"
    );
}

/// AES-128-CTR's schedule waits for the selection relation (#526's third slice): the first lookup's
/// key, a gather of the key's bytes, is a selection's output. The report already counts its 3
/// stages.
#[test]
fn aes_ctr_waits_for_the_selection_relation() {
    let tables = AesTables {
        sbox: TableId(0),
        mul2: TableId(1),
        mul3: TableId(2),
        xor: TableId(3),
    };
    let specs = vec![
        spec(0, TableKind::AesSbox),
        spec(1, TableKind::Gf256Mul { c: 2 }),
        spec(2, TableKind::Gf256Mul { c: 3 }),
        spec(3, TableKind::Bitwise8 { op: BitOp::Xor }),
    ];
    for blocks in [1, 3] {
        let mut g = GraphBuilder::new();
        let inputs = aes128_ctr_inputs(blocks).map(|d| g.input(d).expect("an input"));
        aes128_ctr(&mut g, &tables, inputs, blocks).expect("the circuit");
        let graph = g.finish();
        assert_eq!(refusal(layerless(&graph, &specs)), MAPS, "{blocks} blocks");
        assert_eq!(stage_count(&graph), 3, "{blocks} blocks");
    }
}
