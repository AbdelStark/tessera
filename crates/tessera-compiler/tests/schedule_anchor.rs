/// A node a test adds to a template's layer, reading its checkpoint `c` or the public input `p`
/// that every layer shares; the tensor it adds to the layer's key, if any.
type Extra = fn(&mut GraphBuilder, TensorId, TensorId) -> Option<TensorId>;

/// Two layers of `x ↦ requant(x² + extra(x))`, `extra` adding the template's own node.
fn template(extra: Extra) -> (Graph, Vec<TensorId>) {
    let mut g = GraphBuilder::new();
    let x = g.input(decl(&[4, 8], ADVICE, -100, 100)).expect("x");
    let p = g.input(decl(&[4, 8], NodeKind::Public, 0, 1)).expect("p");
    let unit = g.constant(vec![1]).expect("a constant");
    let mut c = one(&mut g, Op::ConstMul { c: unit }, &[x], out(&[4, 8], ADVICE));
    let mut checkpoints = vec![c];
    for _ in 0..2 {
        let square = one(&mut g, mul(), &[c, c], virt(&[4, 8]));
        let key = match extra(&mut g, c, p) {
            Some(t) => one(&mut g, Op::Add, &[square, t], virt(&[4, 8])),
            None => square,
        };
        c = requant(&mut g, key, &[4, 8], -100, 100);
        checkpoints.push(c);
    }
    (g.finish(), checkpoints)
}

/// The S-box as table 0 and `Gf256Mul { 2 }`, which maps 0 to 0, as table 1.
fn byte_tables() -> Vec<TableSpec> {
    vec![
        spec(0, TableKind::AesSbox),
        spec(1, TableKind::Gf256Mul { c: 2 }),
    ]
}

fn layered(extra: Extra) -> Result<StageSchedule, CompileError> {
    let (graph, checkpoints) = template(extra);
    derive_graph_schedule(&graph, &byte_tables(), &checkpoints, None)
}

/// RFC-0072 'Graphs without layers' 'Not inside a layer': a template holding a `ConstAdd`, a
/// selection, a per-channel `ConstMul`, a `BitDecompose` or an `AssertEqual` is refused. A
/// constant of one value is a scalar whatever its last axis, and `BitFn` stacks.
#[test]
fn a_layer_template_holds_no_operation_whose_stacked_form_is_unspecified() {
    let refused: [(&str, Extra); 6] = [
        ("ConstAdd", |g, c, _| {
            let k = g.constant(vec![3]).expect("a constant");
            Some(one(g, Op::ConstAdd { c: k }, &[c], virt(&[4, 8])))
        }),
        ("Slice", |g, c, _| {
            let op = Op::Slice {
                axis: 1,
                start: 0,
                len: 8,
            };
            Some(one(g, op, &[c], virt(&[4, 8])))
        }),
        ("GatherPublic", |g, c, _| {
            let index = g.constant(vec![3, 2, 1, 0]).expect("rows");
            Some(one(g, Op::GatherPublic { index }, &[c], virt(&[4, 8])))
        }),
        ("ConstMul per channel", |g, c, _| {
            let k = g.constant((1..=8).collect()).expect("a constant");
            Some(one(g, Op::ConstMul { c: k }, &[c], virt(&[4, 8])))
        }),
        ("BitDecompose", |g, c, _| {
            let op = Op::BitDecompose { low: 8, high: 0 };
            g.node(op, &[c], vec![out(&[4, 8, 8], ADVICE)])
                .expect("bits");
            None
        }),
        ("AssertEqual", |g, c, _| {
            g.node(Op::AssertEqual, &[c, c], Vec::new())
                .expect("an equality");
            None
        }),
    ];
    for (name, extra) in refused {
        assert_eq!(refusal(layered(extra)), TEMPLATE, "{name}");
    }
    // One value on a last axis of 8, and on a last axis of 1: scalars.
    let scalar = layered(|g, c, _| {
        let k = g.constant(vec![3]).expect("a constant");
        Some(one(g, Op::ConstMul { c: k }, &[c], virt(&[4, 8])))
    })
    .expect("a scalar ConstMul stacks");
    assert_eq!(scalar.layers.count, 2);
    layered(|g, c, _| {
        let column = one(g, Op::Reshape, &[c], virt(&[4, 8, 1]));
        let k = g.constant(vec![3]).expect("a constant");
        let scaled = one(g, Op::ConstMul { c: k }, &[column], virt(&[4, 8, 1]));
        Some(one(g, Op::Reshape, &[scaled], virt(&[4, 8])))
    })
    .expect("one value on a last axis of 1 is a scalar");
    // A Boolean function stacks as any relation does: stage 1 proves it stacked over the layers.
    let stacked = layered(|g, c, _| {
        let z = g
            .node(Op::BitFn { f: BoolFn::Xor }, &[c, c], vec![virt(&[4, 8])])
            .expect("a BitFn");
        Some(z[0])
    })
    .expect("BitFn may sit in a template");
    let xor = stacked.stages[1]
        .instances
        .iter()
        .find(|i| i.relation == Relation::BitFn(BoolFn::Xor))
        .expect("a stacked BitFn");
    assert!(matches!(xor.layers, Layers::Eq(_)));
    assert_eq!(xor.vars, 5 + stacked.layers.vars);
}

