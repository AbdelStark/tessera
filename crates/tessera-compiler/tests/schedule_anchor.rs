/// Committed `a`, `b` and `c` of `[3, 8]` and a weight: `s = a·b + W·c` requantized, its sum of
/// squares over its channels requantized, and `3a` committed. The graph and its tensors `s` and
/// `a`.
fn products() -> (Graph, TensorId, TensorId) {
    let mut g = GraphBuilder::new();
    let a = g.input(decl(&[3, 8], ADVICE, -100, 100)).expect("a");
    let b = g.input(decl(&[3, 8], ADVICE, -100, 100)).expect("b");
    let c = g.input(decl(&[3, 8], ADVICE, -100, 100)).expect("c");
    let weight = WeightRef {
        ty: WeightType::Q,
        layer: 0,
    };
    let w = g.weight(weight, 8, 8).expect("a weight");
    let m = one(&mut g, mul(), &[a, b], virt(&[3, 8]));
    let p = one(&mut g, Op::MatMulWeight { weight }, &[c, w], virt(&[3, 8]));
    let s = one(&mut g, Op::Add, &[m, p], virt(&[3, 8]));
    let q = one(&mut g, Op::SumSquares { axis: 1 }, &[s], virt(&[3]));
    requant(&mut g, q, &[3], -128, 127);
    requant(&mut g, s, &[3, 8], -128, 127);
    let three = g.constant(vec![3]).expect("a constant");
    one(
        &mut g,
        Op::ConstMul { c: three },
        &[a],
        out(&[3, 8], ADVICE),
    );
    (g.finish(), s, a)
}

/// RFC-0072 'Graphs without layers', RFC-0037 'Layers and kinds' 'No checkpoint': `L = 0`, `λ =
/// 0`, every node outside the layers and every kind a tensor's; with no logits no claim on them.
#[test]
fn a_graph_without_checkpoints_has_no_layers() {
    let (graph, s, _) = products();
    let schedule = layerless(&graph, &[]).expect("a schedule");
    assert_eq!((schedule.layers.count, schedule.layers.vars), (0, 0));
    assert_eq!(schedule.sites.len(), 2, "the two requantizations' inputs");
    assert!(
        schedule
            .sites
            .iter()
            .all(|s| matches!(s, LeafSite::Gadget { .. })),
        "no logits site: {:?}",
        schedule.sites
    );
    for stage in &schedule.stages {
        for claim in &stage.claims {
            assert_eq!(claim.layers, Layers::None);
            assert!(!claim.point.iter().any(|c| matches!(c, Coord::Layer(_))));
        }
        for instance in &stage.instances {
            assert_eq!(instance.layers, Layers::None);
        }
    }
    // Stage 1: the sum of squares, the split key's product and matmul, and the zero-check of `3a`;
    // stage 2: the product and matmul below the sum of squares.
    assert_eq!(schedule.stages[1].instances.len(), 4);
    assert_eq!(schedule.stages[2].instances.len(), 2);
    assert_eq!(schedule.stage_count(), 3);
    assert_eq!(schedule.stage_count(), stage_count(&graph) as usize);
    // With logits, the leaf stage leaves one claim on them, last.
    let with = derive_graph_schedule(&graph, &[], &[], Some(s)).expect("a schedule");
    assert_eq!(with.sites.len(), 3);
    assert_eq!(with.sites.last(), Some(&LeafSite::Logits));
    assert_eq!(with.layers.count, 0);
}

