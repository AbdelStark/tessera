/// RFC-0072 'Public tensors': a public input, and the output of a node that is not gadget-backed
/// whose inputs are all public, through linear maps, products, Boolean functions and selections;
/// never a lookup's, a tensor declared committed, or one with a committed input.
#[test]
fn public_tensors_close_over_every_node_but_the_gadgets() {
    let mut g = GraphBuilder::new();
    let p = g.input(decl(&[4], NodeKind::Public, 0, 1)).expect("p");
    let q = g.input(decl(&[4], NodeKind::Public, 0, 1)).expect("q");
    let a = g.input(decl(&[4], ADVICE, 0, 1)).expect("a");
    let w = g.input(decl(&[4], WEIGHT, 0, 1)).expect("w");
    let product = one(&mut g, mul(), &[p, q], virt(&[4]));
    let xor = one(&mut g, Op::BitFn { f: BoolFn::Xor }, &[p, q], virt(&[4]));
    let rows = g.constant(vec![3, 1]).expect("rows");
    let picked = one(&mut g, Op::GatherPublic { index: rows }, &[xor], virt(&[2]));
    let cut = one(
        &mut g,
        Op::Slice {
            axis: 0,
            start: 1,
            len: 2,
        },
        &[product],
        virt(&[2]),
    );
    let both = one(&mut g, Op::Add, &[picked, cut], virt(&[2]));
    let three = g.constant(vec![3]).expect("a constant");
    let scaled = one(&mut g, Op::ConstAdd { c: three }, &[both], virt(&[2]));
    let looked = one(
        &mut g,
        Op::TableMap { table: TableId(0) },
        &[p],
        out(&[4], NodeKind::LookupOutput { table: TableId(0) }),
    );
    let declared = one(&mut g, Op::ConstMul { c: three }, &[p], out(&[4], ADVICE));
    let mixed = one(&mut g, mul(), &[p, a], virt(&[4]));
    let weighted = one(&mut g, Op::Add, &[q, w], virt(&[4]));
    let after_lookup = one(&mut g, Op::Add, &[looked, p], virt(&[4]));
    let after_commit = one(&mut g, Op::Sub, &[declared, q], virt(&[4]));
    let graph = g.finish();
    let public = public_tensors(&graph);
    assert_eq!(public.len(), graph.tensors.len());
    let expected = [
        (p, true, "a public input"),
        (q, true, "a public input"),
        (a, false, "a committed input"),
        (w, false, "a weight"),
        (product, true, "a Mul of public tensors"),
        (xor, true, "a BitFn of public tensors"),
        (picked, true, "a GatherPublic of a public tensor"),
        (cut, true, "a Slice of a public tensor"),
        (both, true, "an Add of public tensors"),
        (scaled, true, "a ConstAdd of a public tensor"),
        (looked, false, "a lookup of a public tensor"),
        (
            declared,
            false,
            "a public tensor's ConstMul declared committed",
        ),
        (mixed, false, "a Mul with a committed operand"),
        (weighted, false, "an Add with a weight"),
        (after_lookup, false, "an Add with a lookup's output"),
        (after_commit, false, "an Add with a committed tensor"),
    ];
    for (tensor, is, what) in expected {
        assert_eq!(public[tensor.0 as usize], is, "{what}");
    }
}

/// A tiny Llama model of `layers` layers over `n` positions, two query heads of 128 and one key
/// and value head, lowered, as the schedule tests lower it.
fn tiny_llama(profile: Profile, layers: u32, n: u32, classed: bool) -> tessera_compiler::Lowering {
    let (mut arch, mut quant, silu) = llama(profile, layers, 256, 2, 1, 512);
    arch.vocab = 300;
    arch.max_context = 16;
    if classed {
        for layer in 0..layers {
            let at = QuantPoint::Layer {
                layer,
                site: Site::V,
            };
            let set = quant
                .shift_class_sets
                .iter_mut()
                .find(|(p, _)| *p == at)
                .expect("a pot site");
            let r = set.1[0];
            set.1 = vec![r, r + 1];
        }
    }
    let model = PublicModel {
        arch: &arch,
        profile,
        quant: &quant,
        silu_in_exponents: &silu,
    };
    lower(model, n).expect("the model lowers")
}

/// RFC-0072 'Goals': the Llama graphs' schedules are unchanged. Their only public tensors are their
/// public inputs, the positions, so no claim reaches a public atom; and none of their lookups is
/// non-zero at padding, so no sum over a padded axis is refused, `PV`'s over the keys among them.
#[test]
fn no_llama_lowering_has_a_derived_public_tensor_or_a_lookup_non_zero_at_padding() {
    for profile in [Profile::Servable, Profile::Minimal] {
        for (layers, n, classed) in [(2, 5, false), (3, 3, true)] {
            let lowering = tiny_llama(profile, layers, n, classed);
            let graph = &lowering.graph;
            let public = public_tensors(graph);
            let produced: Vec<bool> = graph
                .tensors
                .iter()
                .map(|t| graph.nodes.iter().any(|n| n.outputs.contains(&t.id)))
                .collect();
            for (t, spec) in graph.tensors.iter().enumerate() {
                let input = !produced[t] && spec.kind == NodeKind::Public;
                assert_eq!(public[t], input, "{profile:?}, tensor {t}");
            }
            assert!(public[lowering.positions.0 as usize]);
            for node in &graph.nodes {
                assert_eq!(
                    nonzero_at_padding(graph, &lowering.tables, node),
                    Ok(false),
                    "{profile:?}, node {} ({})",
                    node.id.0,
                    node.op.name()
                );
            }
        }
    }
}

/// RFC-0072 'Public tensors' 'Their claims': a claim on a public tensor is the verifier's to
/// evaluate, as a public atom, which the schedule does not derive yet. Until it does, the claim is
/// refused at the public tensor itself, by the closure, not at a relation below it: a product or a
/// selection of public inputs, and a public input read directly.
#[test]
fn a_claim_on_a_public_tensor_is_refused_until_public_atoms() {
    // The schedule of `requant(key(p, q))`, `key` of `shape`.
    let schedule = |key: fn(&mut GraphBuilder, TensorId, TensorId) -> TensorId, shape: &[u32]| {
        let mut g = GraphBuilder::new();
        let p = g.input(decl(&[4, 8], NodeKind::Public, 0, 1)).expect("p");
        let q = g.input(decl(&[4, 8], NodeKind::Public, 0, 1)).expect("q");
        let k = key(&mut g, p, q);
        requant(&mut g, k, shape, -128, 127);
        layerless(&g.finish(), &[])
    };
    assert_eq!(
        refusal(schedule(
            |g, p, q| one(g, mul(), &[p, q], virt(&[4, 8])),
            &[4, 8]
        )),
        "a claim reaches a public tensor",
        "a Mul of public inputs"
    );
    assert_eq!(
        refusal(schedule(
            |g, p, _| {
                let op = Op::Slice {
                    axis: 0,
                    start: 1,
                    len: 2,
                };
                one(g, op, &[p], virt(&[2, 8]))
            },
            &[2, 8]
        )),
        "a claim reaches a public tensor",
        "a Slice of a public input"
    );
    assert_eq!(
        refusal(schedule(|_, p, _| p, &[4, 8])),
        "a claim reaches a public graph input"
    );
}

// ----- Graphs without layers ---------------------------------------------------------------------

/// Committed `a`, `b` and `c` of `[3, 8]` and a weight: `s = a·b + W·c` requantized, its sum of
/// squares over its channels requantized, and `3a` committed. The graph and its tensors `s` and
/// `a`.
fn products() -> (Graph, TensorId, TensorId) {
    let mut g = GraphBuilder::new();
    let a = g.input(decl(&[3, 8], ADVICE, -100, 100)).expect("a");
    let b = g.input(decl(&[3, 8], ADVICE, -100, 100)).expect("b");
    let c = g.input(decl(&[3, 8], ADVICE, -100, 100)).expect("c");
    let weight = WeightRef {
        ty: WeightType::Q,
        layer: 0,
    };
    let w = g.weight(weight, 8, 8).expect("a weight");
    let m = one(&mut g, mul(), &[a, b], virt(&[3, 8]));
    let p = one(&mut g, Op::MatMulWeight { weight }, &[c, w], virt(&[3, 8]));
    let s = one(&mut g, Op::Add, &[m, p], virt(&[3, 8]));
    let q = one(&mut g, Op::SumSquares { axis: 1 }, &[s], virt(&[3]));
    requant(&mut g, q, &[3], -128, 127);
    requant(&mut g, s, &[3, 8], -128, 127);
    let three = g.constant(vec![3]).expect("a constant");
    one(
        &mut g,
        Op::ConstMul { c: three },
        &[a],
        out(&[3, 8], ADVICE),
    );
    (g.finish(), s, a)
}

/// RFC-0072 'Graphs without layers', RFC-0037 'Layers and kinds' 'No checkpoint': `L = 0`, `λ =
/// 0`, every node outside the layers and every kind a tensor's; with no logits no claim on them.
#[test]
fn a_graph_without_checkpoints_has_no_layers() {
    let (graph, s, _) = products();
    let schedule = layerless(&graph, &[]).expect("a schedule");
    assert_eq!((schedule.layers.count, schedule.layers.vars), (0, 0));
    assert_eq!(schedule.sites.len(), 2, "the two requantizations' inputs");
    assert!(
        schedule
            .sites
            .iter()
            .all(|s| matches!(s, LeafSite::Gadget { .. })),
        "no logits site: {:?}",
        schedule.sites
    );
    for stage in &schedule.stages {
        for claim in &stage.claims {
            assert_eq!(claim.layers, Layers::None);
            assert!(!claim.point.iter().any(|c| matches!(c, Coord::Layer(_))));
        }
        for instance in &stage.instances {
            assert_eq!(instance.layers, Layers::None);
        }
    }
    // Stage 1: the sum of squares, the split key's product and matmul, and the zero-check of `3a`;
    // stage 2: the product and matmul below the sum of squares.
    assert_eq!(schedule.stages[1].instances.len(), 4);
    assert_eq!(schedule.stages[2].instances.len(), 2);
    assert_eq!(schedule.stage_count(), 3);
    assert_eq!(schedule.stage_count(), stage_count(&graph) as usize);
    // With logits, the leaf stage leaves one claim on them, last.
    let with = derive_graph_schedule(&graph, &[], &[], Some(s)).expect("a schedule");
    assert_eq!(with.sites.len(), 3);
    assert_eq!(with.sites.last(), Some(&LeafSite::Logits));
    assert_eq!(with.layers.count, 0);
}

/// One checkpoint bounds no layer: refused, as the lowering has a layer; none is a graph without
/// layers.
#[test]
fn a_single_checkpoint_is_refused() {
    let (graph, _, a) = products();
    let committed = graph
        .nodes
        .last()
        .map(|n| n.outputs[0])
        .expect("the committed 3a");
    assert_eq!(
        refusal(derive_graph_schedule(&graph, &[], &[committed], None)),
        "the lowering has a layer"
    );
    // A checkpoint must be a node's output, even alone: the input `a` is none.
    assert_eq!(
        refusal(derive_graph_schedule(&graph, &[], &[a, committed], None)),
        "every checkpoint is a node's output"
    );
}

/// RFC-0037 'Stages and their instances' 'Stage count': the report counts the schedule's stages,
/// on graphs without layers of every relation and map the schedule derives.
#[test]
fn the_report_counts_the_schedules_stages_on_graphs_without_layers() {
    let mut graphs: Vec<(&str, Graph)> = vec![("products", products().0)];
    // Nothing to prove: the leaf stage alone.
    let mut g = GraphBuilder::new();
    let x = g.input(decl(&[4, 8], ADVICE, -100, 100)).expect("x");
    one(&mut g, mul(), &[x, x], virt(&[4, 8]));
    graphs.push(("no gadget", g.finish()));
    // A committed product: its zero-check counts itself, and its operand's relations follow.
    let mut g = GraphBuilder::new();
    let x = g.input(decl(&[4, 8], ADVICE, -100, 100)).expect("x");
    let y = g.input(decl(&[4, 8], ADVICE, -100, 100)).expect("y");
    let squares = one(&mut g, mul(), &[x, x], virt(&[4, 8]));
    one(&mut g, mul(), &[squares, y], out(&[4, 8], ADVICE));
    graphs.push(("a committed product of a product", g.finish()));
    // Attention's products, through transposes, an expansion and a sum.
    let mut g = GraphBuilder::new();
    let q = g.input(decl(&[2, 4, 8], ADVICE, -100, 100)).expect("q");
    let k = g.input(decl(&[2, 4, 8], ADVICE, -100, 100)).expect("k");
    let scores = one(
        &mut g,
        Op::MatMulAct {
            transpose_rhs: true,
        },
        &[q, k],
        virt(&[2, 4, 4]),
    );
    let turned = one(
        &mut g,
        Op::Transpose {
            perm: vec![1, 0, 2],
        },
        &[scores],
        virt(&[4, 2, 4]),
    );
    let wide = one(
        &mut g,
        Op::Expand { axis: 0, len: 3 },
        &[turned],
        virt(&[3, 4, 2, 4]),
    );
    let summed = one(&mut g, Op::Sum { axis: 0 }, &[wide], virt(&[4, 2, 4]));
    let values = one(
        &mut g,
        Op::MatMulAct {
            transpose_rhs: false,
        },
        &[scores, k],
        virt(&[2, 4, 8]),
    );
    requant(&mut g, summed, &[4, 2, 4], -128, 127);
    requant(&mut g, values, &[2, 4, 8], -128, 127);
    graphs.push(("attention's products", g.finish()));
    // A one-hot of a sum of squares: its index zero-check reads the sum at stage 1.
    let mut g = GraphBuilder::new();
    let x = g.input(decl(&[5, 8], ADVICE, -100, 100)).expect("x");
    let tokens = one(&mut g, Op::SumSquares { axis: 1 }, &[x], virt(&[5]));
    one(
        &mut g,
        Op::OneHot { vocab: 6 },
        &[tokens],
        out(&[5, 6], ADVICE),
    );
    graphs.push(("a one-hot of a sum of squares", g.finish()));
    // Per-channel multipliers after a matmul, then a scalar scale and a difference.
    let mut g = GraphBuilder::new();
    let x = g.input(decl(&[3, 8], ADVICE, -100, 100)).expect("x");
    let m = g.input(decl(&[8], WEIGHT, 1, 100)).expect("multipliers");
    let weight = WeightRef {
        ty: WeightType::K,
        layer: 0,
    };
    let w = g.weight(weight, 8, 8).expect("a weight");
    let acc = one(&mut g, Op::MatMulWeight { weight }, &[x, w], virt(&[3, 8]));
    let scaled = one(
        &mut g,
        Op::Mul {
            broadcast: Broadcast::Leading,
        },
        &[acc, m],
        virt(&[3, 8]),
    );
    let two = g.constant(vec![2]).expect("a constant");
    let doubled = one(&mut g, Op::ConstMul { c: two }, &[x], virt(&[3, 8]));
    let key = one(&mut g, Op::Sub, &[scaled, doubled], virt(&[3, 8]));
    requant(&mut g, key, &[3, 8], -128, 127);
    graphs.push(("an affine key", g.finish()));
    for (name, graph) in graphs {
        let schedule = layerless(&graph, &[]).unwrap_or_else(|e| panic!("{name}: {e:?}"));
        assert_eq!(
            schedule.stage_count(),
            stage_count(&graph) as usize,
            "{name}"
        );
    }
}

// ----- Refusals ----------------------------------------------------------------------------------

/// A node a test adds to a template's layer, reading its checkpoint `c` or the public input `p`
/// that every layer shares; the tensor it adds to the layer's key, if any.
type Extra = fn(&mut GraphBuilder, TensorId, TensorId) -> Option<TensorId>;

/// Two layers of `x ↦ requant(x² + extra(x))`, `extra` adding the template's own node.
fn template(extra: Extra) -> (Graph, Vec<TensorId>) {
    let mut g = GraphBuilder::new();
    let x = g.input(decl(&[4, 8], ADVICE, -100, 100)).expect("x");
    let p = g.input(decl(&[4, 8], NodeKind::Public, 0, 1)).expect("p");
    let unit = g.constant(vec![1]).expect("a constant");
    let mut c = one(&mut g, Op::ConstMul { c: unit }, &[x], out(&[4, 8], ADVICE));
    let mut checkpoints = vec![c];
    for _ in 0..2 {
        let square = one(&mut g, mul(), &[c, c], virt(&[4, 8]));
        let key = match extra(&mut g, c, p) {
            Some(t) => one(&mut g, Op::Add, &[square, t], virt(&[4, 8])),
            None => square,
        };
        c = requant(&mut g, key, &[4, 8], -100, 100);
        checkpoints.push(c);
    }
    (g.finish(), checkpoints)
}

/// The S-box as table 0 and `Gf256Mul { 2 }`, which maps 0 to 0, as table 1.
fn byte_tables() -> Vec<TableSpec> {
    vec![
        spec(0, TableKind::AesSbox),
        spec(1, TableKind::Gf256Mul { c: 2 }),
    ]
}

fn layered(extra: Extra) -> Result<StageSchedule, CompileError> {
    let (graph, checkpoints) = template(extra);
    derive_graph_schedule(&graph, &byte_tables(), &checkpoints, None)
}

/// RFC-0072 'Graphs without layers' 'Not inside a layer': a template holding a `ConstAdd`, a
/// selection, a per-channel `ConstMul`, a `BitDecompose` or an `AssertEqual` is refused. A
/// constant of one value is a scalar whatever its last axis, and `BitFn` stacks.
#[test]
fn a_layer_template_holds_no_operation_whose_stacked_form_is_unspecified() {
    let refused: [(&str, Extra); 6] = [
        ("ConstAdd", |g, c, _| {
            let k = g.constant(vec![3]).expect("a constant");
            Some(one(g, Op::ConstAdd { c: k }, &[c], virt(&[4, 8])))
        }),
        ("Slice", |g, c, _| {
            let op = Op::Slice {
                axis: 1,
                start: 0,
                len: 8,
            };
            Some(one(g, op, &[c], virt(&[4, 8])))
        }),
        ("GatherPublic", |g, c, _| {
            let index = g.constant(vec![3, 2, 1, 0]).expect("rows");
            Some(one(g, Op::GatherPublic { index }, &[c], virt(&[4, 8])))
        }),
        ("ConstMul per channel", |g, c, _| {
            let k = g.constant((1..=8).collect()).expect("a constant");
            Some(one(g, Op::ConstMul { c: k }, &[c], virt(&[4, 8])))
        }),
        ("BitDecompose", |g, c, _| {
            let op = Op::BitDecompose { low: 8, high: 0 };
            g.node(op, &[c], vec![out(&[4, 8, 8], ADVICE)])
                .expect("bits");
            None
        }),
        ("AssertEqual", |g, c, _| {
            g.node(Op::AssertEqual, &[c, c], Vec::new())
                .expect("an equality");
            None
        }),
    ];
    for (name, extra) in refused {
        assert_eq!(refusal(layered(extra)), TEMPLATE, "{name}");
    }
    // One value on a last axis of 8, and on a last axis of 1: scalars.
    let scalar = layered(|g, c, _| {
        let k = g.constant(vec![3]).expect("a constant");
        Some(one(g, Op::ConstMul { c: k }, &[c], virt(&[4, 8])))
    })
    .expect("a scalar ConstMul stacks");
    assert_eq!(scalar.layers.count, 2);
    layered(|g, c, _| {
        let column = one(g, Op::Reshape, &[c], virt(&[4, 8, 1]));
        let k = g.constant(vec![3]).expect("a constant");
        let scaled = one(g, Op::ConstMul { c: k }, &[column], virt(&[4, 8, 1]));
        Some(one(g, Op::Reshape, &[scaled], virt(&[4, 8])))
    })
    .expect("one value on a last axis of 1 is a scalar");
    // A Boolean function stacks as any relation does (its relation is #526's third slice).
    layered(|g, c, _| {
        g.node(Op::BitFn { f: BoolFn::Xor }, &[c, c], vec![virt(&[4, 8])])
            .expect("a BitFn");
        None
    })
    .expect("BitFn may sit in a template");
}

/// RFC-0072 'Not inside a layer', after its final review: a template position whose node's output
/// is public, a product of public tensors or a transpose of one, is refused too, whether or not a
/// claim reaches it, since a public tensor's padded layers are not specified. A product with the
/// checkpoint is not public: the rule admits it, and the claim on the public operand that every
/// layer shares is then refused, as it is today.
#[test]
fn a_layer_template_holds_no_public_tensor() {
    let refused: [(&str, Extra); 2] = [
        ("a product of public tensors", |g, _, p| {
            Some(one(g, mul(), &[p, p], virt(&[4, 8])))
        }),
        ("a transpose of a public tensor, unread", |g, _, p| {
            let op = Op::Transpose { perm: vec![1, 0] };
            one(g, op, &[p], virt(&[8, 4]));
            None
        }),
    ];
    for (name, extra) in refused {
        assert_eq!(refusal(layered(extra)), TEMPLATE, "{name}");
    }
    assert_eq!(
        refusal(layered(|g, c, p| Some(one(
            g,
            mul(),
            &[c, p],
            virt(&[4, 8])
        )))),
        "a claim in a layer reaches a tensor that every layer shares",
        "a product with the checkpoint"
    );
}

/// RFC-0072 'Not inside a layer', after its review: a template position holding a lookup
/// non-zero at padding, an S-box or a requantization into `[1, 100]`, is refused, since its padded
