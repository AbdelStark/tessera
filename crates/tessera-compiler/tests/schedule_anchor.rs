//! The schedule of graphs that are not a Llama lowering (RFC-0072, #526's first slice): graphs
//! with no checkpoint and no logits, public tensors, and the refusals RFC-0072 adds.
//!
//! - **Graphs without layers.** With no checkpoint every node is outside the layers: no kind is
//!   stacked, no point has a layer coordinate, and with no logits the leaf stage leaves no claim on
//!   them. One checkpoint, which bounds no layer, is refused.
//! - **Public tensors.** A public input, and the output of a node that is not gadget-backed whose
//!   inputs are all public, unless it is declared committed. No Llama lowering has one but its
//!   public inputs.
//! - **The stage count.** The commitment report's is the schedule's on every graph without layers
//!   built here.
//! - **The refusals**, each `ERR-INTERNAL` with its rule, and the case each admits: a layer
//!   template holding an operation whose stacked form RFC-0072 leaves unspecified; a committed
//!   output of a node stage 1 does not prove; a sum over an axis that is not a power of two, unless
//!   an input it sums is 0 at the axis's padded positions; and, until stage 1 derives them, the bit
//!   operations' zero-checks.
//! - **Padding.** A lookup is non-zero at padding exactly when its table, generated by
//!   `tessera_tables`, maps the zero key to a non-zero value in some class; a requantization when
//!   RFC-0005's `rq(0)` is not 0. No Llama lowering has one.

